#!/usr/bin/env node
// @ts-check

/**
 * extract-encoding-fixtures.mjs — M0-REPAIR-ENCODING.
 *
 * Lifts real corrupted strings out of the frozen archive into a
 * committed fixture file, so the repair is tested against the data it
 * exists for rather than against invented examples — and so the tests
 * still run on a clone that has no archive (the archive is 143 MB and
 * gitignored).
 *
 * Regenerate after any change to the frozen inputs; the manifest
 * digests in data/archive-manifest.json say when that has happened.
 *
 * Usage: node tools/extract-encoding-fixtures.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { readWorkbook } from './lib/xlsx.mjs';
import { decodeMacRoman, repairMojibake, repairText } from './lib/text-repair.mjs';

const ARCHIVE = 'Pre August 2026';
const OUT = 'tools/test/fixtures/encoding.json';
const SHEETS = [
  'Vinyl Records Record 2 Jen.xlsx',
  '1st load to add.xlsx',
  '2nd load to add.xlsx',
];

/** @type {{raw: string, expected: string, kind: string, source: string}[]} */
const cases = [];
const seen = new Set();
const add = (/** @type {string} */ raw, /** @type {string} */ kind, /** @type {string} */ source) => {
  const expected = repairText(raw);
  if (expected === raw || seen.has(raw)) return;
  seen.add(raw);
  cases.push({ raw, expected, kind, source });
};

// String-level: mojibake and stray invisibles inside the workbooks.
for (const file of SHEETS) {
  const wb = readWorkbook(`${ARCHIVE}/${file}`);
  for (const sheet of wb.order) {
    for (const row of wb.sheets[sheet]) {
      for (const value of Object.values(row)) {
        const kind = repairMojibake(value) !== value ? 'mojibake' : 'invisible';
        add(value, kind, `${file}:${sheet}`);
      }
    }
  }
}

// Byte-level: the CSV is MacRoman on disk, so its fixtures are the
// decoded strings — that decode is the repair under test.
const csv = 'classical vinyl list in progress.csv';
for (const field of decodeMacRoman(readFileSync(`${ARCHIVE}/${csv}`)).split(/[\t\n]/)) {
  add(field, 'macroman-file', csv);
}

// Cap the bulk categories: 324 near-identical CRLF track listings
// prove nothing the first few do not, and a fixture file nobody reads
// is not a test. Mojibake cases are kept in full — there are 7.
const capped = [];
const perKind = new Map();
for (const c of cases) {
  const n = (perKind.get(c.kind) ?? 0) + 1;
  perKind.set(c.kind, n);
  if (c.kind === 'mojibake' || n <= 12) capped.push(c);
}

/**
 * Negative controls. These must survive the repair untouched: each is
 * legitimate text that a careless mojibake pass would corrupt.
 * `√` and `•` are the exact characters MacRoman mojibake produces.
 */
const negatives = [
  { raw: 'Side A • Side B', why: 'a real bullet, not the tail of a mojibake pair' },
  { raw: '√2 is irrational', why: 'a real radical, the commonest mojibake lead byte' },
  { raw: 'Café de Paris', why: 'correctly-encoded e-acute must not be re-decoded' },
  { raw: 'Play Bach – 6 Masterpieces', why: 'correctly-encoded en dash' },
  { raw: 'Shéhérazade / Les Nuits d’été', why: 'accented French with a curly apostrophe' },
  { raw: 'Symphony No.2 “Romantic”', why: 'curly quotes are not corruption' },
];

writeFileSync(OUT, `${JSON.stringify({
  $comment: 'M0-REPAIR-ENCODING fixtures. Generated by tools/extract-encoding-fixtures.mjs from the frozen archive — never hand-edit.',
  archive: ARCHIVE,
  counts: Object.fromEntries(perKind),
  cases: capped,
  negatives,
}, null, 2)}\n`);

console.log(`extract-encoding-fixtures: wrote ${OUT} — ${capped.length} cases (of ${cases.length} found), ${negatives.length} negatives`);
console.log(`  by kind: ${[...perKind].map(([k, v]) => `${k}=${v}`).join(', ')}`);
